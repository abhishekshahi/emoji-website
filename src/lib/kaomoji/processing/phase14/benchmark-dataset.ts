export function evaluateBenchmark(
  searchFn: (query: string, limit: number) => number,
): { pass: number; total: number; pass_rate: number; zero_result_rate: number; failures: readonly { query: string; got: number; min: number }[] } {
  let pass = 0;
  let zeroResults = 0;
  const failures: { query: string; got: number; min: number }[] = [];
  for (const tc of SEARCH_BENCHMARK_V1) {
    const got = searchFn(tc.query, 12);
    if (tc.expect_zero) {
      if (got === 0) pass++;
      else failures.push({ query: tc.query, got, min: 0 });
    } else {
      if (got === 0) zeroResults++;
      if (got >= tc.min_results) pass++;
      else failures.push({ query: tc.query, got, min: tc.min_results });
    }
  }
  const total = SEARCH_BENCHMARK_V1.length;
  return {
    pass,
    total,
    pass_rate: total > 0 ? pass / total : 0,
    zero_result_rate: total > 0 ? zeroResults / total : 0,
    failures,
  };
}